// Script para generar TODO.md y actualizar WelcomeOverlay.svelte automáticamente desde abil_name.ts (CommonJS)
const fs = require("fs");
const path = require("path");

const abilPath = path.join(
  __dirname,
  "..",
  "src",
  "lib",
  "gcsim-to-multiopt",
  "config",
  "abil_name.ts"
);
const todoPath = path.join(__dirname, "..", "TODO.md");
const welcomeOverlayPath = path.join(
  __dirname,
  "..",
  "src",
  "lib",
  "components",
  "WelcomeOverlay.svelte"
);

const abilFile = fs.readFileSync(abilPath, "utf8");

// Extraer el objeto characterAbils usando regex
const characterAbilsMatch = abilFile.match(
  /const characterAbils[^{]*{([\s\S]*?)^};/m
);
if (!characterAbilsMatch) {
  console.error("No se pudo encontrar el objeto characterAbils");
  process.exit(1);
}

const characterAbilsContent = characterAbilsMatch[1];
const lines = characterAbilsContent.split(/\r?\n/);

// Regex para detectar definiciones de personaje
const charDefRegex = /^\s*([a-zA-Z0-9_]+)\s*:\s*{\s*$/;
// Regex para detectar líneas de habilidad ("...": [)
const abilLine = /^\s*"(.+?)"\s*:/;

let chars = [];
let currentChar = null;
let currentHasAbil = false;
let braceLevel = 0;

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];

  // Detectar inicio de definición de personaje
  const charMatch = line.match(charDefRegex);
  if (charMatch && braceLevel === 0) {
    if (currentChar) {
      chars.push({ name: currentChar, mapped: currentHasAbil });
    }
    currentChar = charMatch[1];
    currentHasAbil = false;
    braceLevel = 1;
    continue;
  }

  // Contar llaves para saber cuándo termina la definición del personaje
  const openBraces = (line.match(/{/g) || []).length;
  const closeBraces = (line.match(/}/g) || []).length;
  braceLevel += openBraces - closeBraces;

  // Si estamos dentro de la definición de un personaje y encontramos una habilidad
  if (currentChar && braceLevel > 0 && abilLine.test(line)) {
    currentHasAbil = true;
  }

  // Si braceLevel llega a 0, terminó la definición del personaje actual
  if (currentChar && braceLevel === 0) {
    chars.push({ name: currentChar, mapped: currentHasAbil });
    currentChar = null;
    currentHasAbil = false;
  }

  // También detectar personajes con objetos vacíos en una sola línea (ej: "heizou: {},")
  const emptyCharMatch = line.match(/^\s*([a-zA-Z0-9_]+)\s*:\s*{\s*}\s*,?\s*$/);
  if (emptyCharMatch && braceLevel === 0) {
    chars.push({ name: emptyCharMatch[1], mapped: false });
  }
}

// Push last character si quedó pendiente
if (currentChar) {
  chars.push({ name: currentChar, mapped: currentHasAbil });
}

// Orden alfabético
chars.sort((a, b) => a.name.localeCompare(b.name, "es"));

function formatDisplayName(rawName) {
  const cleanName = rawName.replace(/[-\s]+$/, "");
  if (cleanName.startsWith("traveler") && cleanName !== "traveler") {
    const element = cleanName.substring(8);
    let elementName;
    if (element === "anemo") elementName = "Anemo";
    else if (element === "geo") elementName = "Geo";
    else if (element === "electro") elementName = "Electro";
    else if (element === "dendro") elementName = "Dendro";
    else if (element === "hydro") elementName = "Hydro";
    else if (element === "pyro") elementName = "Pyro";
    else if (element === "cryo") elementName = "Cryo";
    else elementName = element.charAt(0).toUpperCase() + element.slice(1);
    return `Traveler ${elementName}`;
  }
  return cleanName.charAt(0).toUpperCase() + cleanName.slice(1);
}

const total = chars.length;
const done = chars.filter((c) => c.mapped).length;
const pending = total - done;
const percent = total > 0 ? ((done / total) * 100).toFixed(1) : "0.0";

const dateStr = new Date().toLocaleString("es-MX", {
  dateStyle: "short",
  timeStyle: "short",
});

// 1. Actualizar TODO.md
let extraSections = "";
if (fs.existsSync(todoPath)) {
  const existingTodo = fs.readFileSync(todoPath, "utf8");
  const notesMatch = existingTodo.match(/(## Note on buffs[\s\S]*)$/);
  if (notesMatch) {
    extraSections = "\n" + notesMatch[1].trimEnd() + "\n";
  }
}

const header = `# TODO: Tracking of Pending Characters in abil_name.ts\n\nThis file is automatically generated from the \`characterAbils\` object in \`abil_name.ts\`.\nMark characters as their abilities are added.\n\n---\n\n**Updated:** ${dateStr}\n\n- Total characters: ${total}\n- Mapped: ${done}\n- Pending: ${pending}\n- Completion percentage: ${percent}%\n\n## Character Status\n\n| Character | Status |\n|-----------|--------|`;

const table = chars
  .map((c) => {
    const displayName = formatDisplayName(c.name);
    const emote = c.mapped ? "✅" : "⬜";
    return `| ${displayName} | ${emote} |`;
  })
  .join("\n");

const footer = `\n---\n\n> Update this list as you add character mappings or new characters.\n`;

fs.writeFileSync(todoPath, header + "\n" + table + footer + extraSections, "utf8");
console.log("TODO.md updated automatically.");

// 2. Actualizar WelcomeOverlay.svelte
const pendingCharacters = chars
  .filter((c) => !c.mapped)
  .map((c) => formatDisplayName(c.name))
  .sort((a, b) => a.localeCompare(b, "es"));

const autoGenBlock = `// [AUTO-GENERATED:START]
    const pendingCharacters = [
${pendingCharacters.map((name) => `        '${name}',`).join("\n")}
    ];

    const totalCharacters = ${total};
    const mappedCharacters = ${done};
    const progressPercent = ${percent};
    // [AUTO-GENERATED:END]`;

if (fs.existsSync(welcomeOverlayPath)) {
  let welcomeContent = fs.readFileSync(welcomeOverlayPath, "utf8");
  const markerRegex = /\/\/\s*\[AUTO-GENERATED:START\][\s\S]*?\/\/\s*\[AUTO-GENERATED:END\]/;
  if (markerRegex.test(welcomeContent)) {
    welcomeContent = welcomeContent.replace(markerRegex, autoGenBlock);
    fs.writeFileSync(welcomeOverlayPath, welcomeContent, "utf8");
    console.log(`WelcomeOverlay.svelte updated automatically (${pendingCharacters.length} pending, ${percent}% completed).`);
  } else {
    console.warn("No se encontró el bloque [AUTO-GENERATED:START]...[AUTO-GENERATED:END] en WelcomeOverlay.svelte");
  }
} else {
  console.warn("No se encontró WelcomeOverlay.svelte en:", welcomeOverlayPath);
}
